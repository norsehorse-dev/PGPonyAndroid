// KeyAlgorithm.kt
// PGPony Android
//
// Matches iOS PGPKeyModel.swift KeyAlgorithm enum.
// Maps OpenPGP algorithm IDs + key versions to our internal enum.

package com.pgpony.android.crypto

/**
 * Key algorithm types supported by PGPony.
 * Matches iOS KeyAlgorithm enum for cross-platform parity.
 */
enum class KeyAlgorithm(
    val displayName: String,
    val shortName: String,
    val keyBits: Int,
    val isV6: Boolean = false
) {
    RSA_2048("RSA 2048", "RSA-2048", 2048),
    RSA_3072("RSA 3072", "RSA-3072", 3072),
    RSA_4096("RSA 4096", "RSA-4096", 4096),
    // 4.4.1 (#36): import/label-only. Not offered for generation; these exist
    // so an imported RSA-3072/8192 key is labeled by its real modulus size
    // instead of collapsing to RSA-4096.
    RSA_8192("RSA 8192", "RSA-8192", 8192),
    ED25519_CV25519("Ed25519+Cv25519", "Ed25519", 256),

    // RFC 9580 v6 algorithm variants. V6_ED25519 (Ed25519 cert primary +
    // Ed25519 signing subkey + X25519 encryption subkey) is GENERATED by
    // PGPony as of V6-3. The X25519/Ed448/X448 entries remain import-only —
    // they label keys recognized on parse but are not offered for generation.
    V6_ED25519("Ed25519 (v6)", "Ed25519 v6", 256, isV6 = true),
    V6_X25519("X25519 (v6)", "X25519 v6", 256, isV6 = true),
    V6_ED448("Ed448 (v6)", "Ed448 v6", 448, isV6 = true),
    V6_X448("X448 (v6)", "X448 v6", 448, isV6 = true),

    // 4.0.0 Phase 2b — IETF post-quantum composite (draft-ietf-openpgp-pqc,
    // algorithm 35): ML-KEM-768 + X25519 on a v6 encryption subkey. The
    // primary is Ed25519; this labels the whole key when such a subkey is
    // present. Import + encrypt/decrypt supported; not offered for keygen.
    MLKEM768_X25519_V6("ML-KEM-768+X25519 (v6)", "ML-KEM-768 v6", 0, isV6 = true),

    // 4.5.0 (item 14 / #56): RFC 9980 v4 interop shape — a v4 Ed25519 primary
    // with a v4 algo-35 (ML-KEM-768 + X25519) encryption subkey. Algo 35 is the
    // one PQ code point the RFC allows on v4 (algo 36 stays v6-only), so this is
    // the maximum-reach shape: an ordinary v4 primary every tool handles, with
    // only the encryption subkey needing algo-35 awareness. Stored as raw bytes
    // because BC cannot parse a v4 subkey that carries no material-length field.
    MLKEM768_X25519_V4("ML-KEM-768+X25519 (v4)", "ML-KEM-768 v4", 0),

    // 4.0.0 Phase 2b — LibrePGP post-quantum composite (draft-koch-librepgp,
    // algorithm 8): ML-KEM-768 + X25519 on a v5 encryption subkey under a
    // v4 EdDSA primary (GnuPG 2.5.x keys). Naming rule, settled twice on
    // issue #1 during 4.2.0-RC1: display names follow RFC 9980 (ML-KEM),
    // for BOTH wire formats, because the RFC names the algorithm and gpg's
    // "kyber"/ky* strings are the deviating side. The generator caption
    // carries the ky768_cv25519 / ky1024_cv448 mapping so gpg users still
    // recognize their keys; the gpg names do not become PGPony's names.
    MLKEM768_X25519_LIBREPGP("ML-KEM-768+X25519 (LibrePGP)", "ML-KEM-768 v5", 0),

    // 4.2.0 §1.1 — IETF post-quantum composite (draft-ietf-openpgp-pqc,
    // algorithm 36): ML-KEM-1024 + X448 on a v6 encryption subkey. Distinct
    // code point from algo 35, so it needs no material inspection to label.
    MLKEM1024_X448_V6("ML-KEM-1024+X448 (v6)", "ML-KEM-1024 v6", 0, isV6 = true),

    // 4.2.0 §1.1 — LibrePGP post-quantum composite (algorithm 8): Kyber/
    // ML-KEM-1024 + X448 on a v5 encryption subkey. Algorithm 8 is SHARED
    // with the 768 variant, so 768-vs-1024 is told apart by the curve OID
    // (X448 1.3.101.111) in detectAlgorithm, not by the algorithm id.
    MLKEM1024_X448_LIBREPGP("ML-KEM-1024+X448 (LibrePGP)", "ML-KEM-1024 v5", 0),

    // 4.3.x (issue #2): ECDSA primary (algorithm 19), an import-only label.
    // GnuPG 2.5.x LibrePGP PQC keys carry an ECDSA primary (for example on
    // brainpoolP512r1 or a NIST curve). Without this entry such a primary fell
    // through detectAlgorithm's catch-all and was mislabeled as RSA 4096. Not
    // offered for generation; PGPony's own keys use an Ed25519 / EdDSA primary.
    ECDSA("ECDSA", "ECDSA", 0),

    // item 17 (Play review): curve-aware ECDSA labels. detectAlgorithm reads
    // the curve OID and maps algo 19 to one of these, so a NIST / brainpool
    // primary shows its real curve instead of "ECDSA" (bits 0) or "RSA 4096".
    // Import-only; keyBits is the curve field size.
    ECDSA_NIST_P256("ECDSA (NIST P-256)", "NIST P-256", 256),
    ECDSA_NIST_P384("ECDSA (NIST P-384)", "NIST P-384", 384),
    ECDSA_NIST_P521("ECDSA (NIST P-521)", "NIST P-521", 521),
    ECDSA_BRAINPOOL_P256("ECDSA (brainpoolP256r1)", "brainpoolP256r1", 256),
    ECDSA_BRAINPOOL_P384("ECDSA (brainpoolP384r1)", "brainpoolP384r1", 384),
    ECDSA_BRAINPOOL_P512("ECDSA (brainpoolP512r1)", "brainpoolP512r1", 512),
    ECDSA_SECP256K1("ECDSA (secp256k1)", "secp256k1", 256),

    // item 17 (Play review): the truthful fallback. A key detectAlgorithm
    // cannot model is labeled Unknown, never a confident wrong "RSA 4096".
    UNKNOWN("Unknown", "Unknown", 0),

    // 4.3.x (issue #2): LibrePGP composite ML-KEM-1024 + brainpoolP384r1
    // (algorithm 8), the pairing gpg 2.5.x / GPG4WIN 5.1 emits. Import and label
    // supported; the KEM (encrypt/decrypt) is gated on gpg round-trip
    // verification. Not offered for generation.
    MLKEM1024_BP384_LIBREPGP("ML-KEM-1024+brainpoolP384r1 (LibrePGP)", "ML-KEM-1024 bp384 v5", 0),

    // 4.4.0 RC3 (#30/#31) - RFC 9980 composite ML-DSA + EdDSA SIGNING keys.
    // Unlike the ML-KEM composites (encryption subkeys), these are v6 signing
    // keys: a composite ML-DSA + EdDSA primary (algo 30/31) that self-certifies
    // and carries an ML-KEM encryption subkey. BouncyCastle rejects the algo
    // 30/31 signatures, so these keys live in the raw-bytes composite path
    // (CompositeKeyFacade / CompositeDocument*), not as a PGPSecretKeyRing.
    // Recognized on import; offered for keygen once wired.
    MLDSA65_ED25519_V6("ML-DSA-65+Ed25519 (v6)", "ML-DSA-65 v6", 0, isV6 = true),
    MLDSA87_ED448_V6("ML-DSA-87+Ed448 (v6)", "ML-DSA-87 v6", 0, isV6 = true);

    /**
     * Whether this algorithm uses native Curve25519 for encryption (ECDH subkey).
     * Used for routing encrypt/decrypt to the native Cv25519 path vs. RSA.
     */
    val usesCv25519: Boolean
        get() = this == ED25519_CV25519 || this == V6_ED25519 || this == V6_X25519

    /** The four ML-KEM composite (post-quantum) algorithms, either format. */
    val isComposite: Boolean
        get() = this == MLKEM768_X25519_V6 || this == MLKEM1024_X448_V6 ||
            this == MLKEM768_X25519_V4 ||
            this == MLKEM768_X25519_LIBREPGP || this == MLKEM1024_X448_LIBREPGP ||
            this == MLKEM1024_BP384_LIBREPGP

    /** The two RFC 9980 composite ML-DSA + EdDSA signing keys (algo 30/31). */
    val isCompositeSign: Boolean
        get() = this == MLDSA65_ED25519_V6 || this == MLDSA87_ED448_V6

    companion object {
        /** Algorithms that can be selected in the key generation UI. */
        // 4.4.0 RC3: keygen picker groups. Organized by security tier, with a
        // de-emphasized Advanced/compatibility bucket (RSA + LibrePGP). The UI
        // renders these; [generatable] stays the flat union for other callers.
        val generatableClassical = listOf(V6_ED25519, ED25519_CV25519)
        val generatablePostQuantum = listOf(
            // The recommended post-quantum keys: RFC 9580 v6 composite encryption
            // and ML-DSA + EdDSA signing. The three ML-KEM-768+X25519 WIRE SHAPES
            // (v6 / v4 / v5) live in [generatableInterop] instead, since they are
            // the same KEM in different formats, a compatibility choice, not a
            // security one.
            MLKEM1024_X448_V6, MLDSA65_ED25519_V6
        )
        // item 14 (#56): the interop tier — the three encodings of the SAME
        // ML-KEM-768 + X25519 key, one per target tool's expectations:
        //   v6  RFC 9580 composite primary (algo 35), PGPony/Sequoia-native
        //   v4  RFC 9980 Ed25519 primary + v4 algo-35 subkey, maximum reach
        //   v5  LibrePGP composite (algo 8), GnuPG 2.5.x
        // Grouped so a tester picks a compatibility target, not a strength.
        val generatableInterop = listOf(
            MLKEM768_X25519_V6, MLKEM768_X25519_V4, MLKEM768_X25519_LIBREPGP
        )
        val generatableAdvanced = listOf(
            RSA_4096, RSA_2048,
            MLKEM1024_X448_LIBREPGP
        )

        /** Every generatable algorithm (the union of the picker groups). */
        val generatable = generatableClassical + generatablePostQuantum +
            generatableInterop + generatableAdvanced

        /**
         * Map an OpenPGP algorithm ID + key version to a KeyAlgorithm.
         * Handles both v4 (RFC 4880) and v6 (RFC 9580) algorithm IDs.
         *
         * Mirrors iOS KeyAlgorithm.from(algorithmID:keyVersion:).
         */
        fun from(algorithmID: Int, keyVersion: Int = 4): KeyAlgorithm? {
            if (keyVersion == 5 && algorithmID == 8) {
                // LibrePGP Kyber+X25519 composite subkey (GnuPG 2.5.x)
                return MLKEM768_X25519_LIBREPGP
            }
            return if (keyVersion == 6) {
                when (algorithmID) {
                    35 -> MLKEM768_X25519_V6  // ML-KEM-768+X25519 composite
                    36 -> MLKEM1024_X448_V6   // ML-KEM-1024+X448 composite
                    30 -> MLDSA65_ED25519_V6  // composite ML-DSA-65+Ed25519 signing
                    31 -> MLDSA87_ED448_V6    // composite ML-DSA-87+Ed448 signing
                    19 -> ECDSA            // ECDSA, unlikely in v6 but valid
                    27 -> V6_ED25519       // Ed25519 signing key
                    25 -> V6_X25519        // X25519 encryption subkey
                    28 -> V6_ED448         // Ed448 signing key
                    26 -> V6_X448          // X448 encryption subkey
                    1, 2, 3 -> RSA_4096    // RSA (can't tell bit size from algo ID)
                    22 -> ED25519_CV25519  // Legacy EdDSA OID — unlikely in v6 but valid
                    18 -> ED25519_CV25519  // Legacy ECDH — unlikely in v6 but valid
                    else -> null
                }
            } else {
                // V4 (RFC 4880)
                when (algorithmID) {
                    1, 2, 3 -> RSA_4096    // RSA — can't tell bit size from algo ID
                    22 -> ED25519_CV25519  // EdDSA (legacy OID-based Ed25519)
                    18 -> ED25519_CV25519  // ECDH (Cv25519 subkey)
                    19 -> ECDSA            // ECDSA (NIST or brainpool signing primary)
                    else -> null
                }
            }
        }
    }
}
