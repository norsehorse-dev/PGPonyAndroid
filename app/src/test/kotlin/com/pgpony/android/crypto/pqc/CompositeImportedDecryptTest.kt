// CompositeImportedDecryptTest.kt
// PGPony Android — 4.5.0 (item 12 / issue #36, Umotas)
//
// Reproduction + diagnostic for the imported-composite-key decrypt failure:
// an ML-KEM key whose primary is a composite ML-DSA (the shape SQ generates),
// imported into PGPony, cannot decrypt a file encrypted to it, failing with
// "no held composite secret key". These keys are not BouncyCastle-parseable,
// so they travel the raw composite path (decrypt's compositePrimaryRings ->
// CompositeDecryptor.findRawComposite -> openRaw).
//
// Two tests split the two candidate causes from the plan:
//   * the PGPony-generated control proves the raw path itself works;
//   * the SQ-fixture test is the actual reported case.
// Control green + SQ red ("no held composite secret key") means the bug is a
// fingerprint mismatch between PGPony's parse of SQ's subkey packet and the
// fingerprint SQ put in the PKESK (candidate b). SQ green means the reported
// failure lives in the ViewModel's compositeRings loading, not the decrypt
// core (candidate a).

package com.pgpony.android.crypto.pqc

import com.pgpony.android.crypto.PGPCryptoService
import org.bouncycastle.bcpg.ArmoredInputStream
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.ByteArrayInputStream

class CompositeImportedDecryptTest {

    private val svc = PGPCryptoService.shared

    private fun res(name: String): ByteArray? =
        javaClass.getResourceAsStream("/pqc/$name")?.use { it.readBytes() }

    private fun deArmor(bytes: ByteArray): ByteArray =
        if (bytes.isNotEmpty() && bytes[0].toInt() == '-'.code)
            ArmoredInputStream(ByteArrayInputStream(bytes)).use { it.readBytes() }
        else bytes

    // Control (CI-safe, no fixture): a composite ML-DSA primary + ML-KEM subkey
    // generated by PGPony, encrypted to and decrypted via the raw composite
    // path. Expected GREEN.
    @Test
    fun `pgpony composite-primary key round-trips through the raw decrypt path`() {
        val secRaw = CompositePrimaryKeyGen.assemble("PQ Import <pq-import@pgpony.app>")
        val pubRaw = CompositeKeyFacade.publicRingOf(secRaw)
        val recipient = CompositeKeyFacade.encryptionSubkeyRing(pubRaw)
        assertTrue("composite key must expose an ML-KEM recipient subkey", recipient != null)

        val plaintext = "imported composite decrypt control #36".toByteArray()
        val message = svc.encrypt(plaintext, listOf(recipient!!))

        val result = svc.decrypt(
            message, secretKeyRings = emptyList(), passphrase = null,
            compositePrimaryRings = listOf(secRaw)
        )
        assertArrayEquals("PGPony composite key must decrypt via the raw path", plaintext, result.data)
    }

    // The actual reported case (item 12 / #36). An SQ-generated composite key
    // imported into PGPony must decrypt a file SQ encrypted to it. Uses the
    // committed SQ fixtures; skips only if they are absent. This is EXPECTED to
    // reproduce the bug (red) until item 12 is fixed.
    @Test
    fun `sq-generated composite key decrypts an sq-encrypted message via the raw path`() {
        val sk = res("sq-sec.pgp")
        val msg = res("sq-msg.pgp")
        assumeTrue("pqc/sq-sec.pgp or sq-msg.pgp absent", sk != null && msg != null)

        val result = svc.decrypt(
            msg!!, secretKeyRings = emptyList(), passphrase = null,
            compositePrimaryRings = listOf(deArmor(sk!!))
        )
        assertTrue("SQ-imported composite key must decrypt the SQ message", result.data.isNotEmpty())
    }

    // The passphrase-protected SQ variant: the composite ML-KEM subkey is
    // AEAD-locked, so the passphrase must reach the raw composite decrypt path
    // (openRaw -> CompositeKeyFacade.parse with the passphrase).
    @Test
    fun `sq protected composite key decrypts with its passphrase via the raw path`() {
        val sk = res("sq-sec-protected.pgp")
        val msg = res("sq-msg-protected.pgp")
        assumeTrue("pqc/sq-*-protected fixtures absent", sk != null && msg != null)

        val result = svc.decrypt(
            msg!!, secretKeyRings = emptyList(), passphrase = "pgpony-test",
            compositePrimaryRings = listOf(deArmor(sk!!))
        )
        assertTrue("protected SQ composite key must decrypt with its passphrase", result.data.isNotEmpty())
    }
}
