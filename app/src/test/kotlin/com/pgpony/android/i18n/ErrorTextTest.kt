    @Test
    fun everyRuleMatchesItsOwnMessage() {
        val wrong = examples.filter { (message, id) -> ErrorText.match(message)?.first?.resId != id }
        assertEquals("messages matched by the wrong rule or by none: " + wrong.map { it.first }, 0, wrong.size)
    }

    @Test
    fun everyRuleHasAnExample() {
        assertEquals(ErrorTextRules.all.size, examples.map { it.second }.toSet().size)
    }

    @Test
    fun unknownTextIsNotMatched() {
        assertNull(ErrorText.match("some library message nobody wrote a rule for"))
    }

    @Test
    fun detailWithoutAnApplicationDropsOperationPrefixes() {
        assertEquals("Incorrect passphrase", ErrorText.detail("Decryption failed: Decryption failed: Incorrect passphrase"))
        assertEquals("Incorrect passphrase", ErrorText.localize("Incorrect passphrase"))
    }
